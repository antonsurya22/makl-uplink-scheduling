# Paired hardware analysis
# ---------------------------------------------------------------------------
def cmd_hardware(args):
    df = pd.read_csv(args.csv)
    if "block" not in df.columns:
        sys.exit("hardware CSV needs a 'block' column identifying matched triples.")
    os.makedirs(args.out, exist_ok=True)
    conds = [c for c in ("Normal", "Moderate", "Severe") if c in set(df.profile)]
    methods = [m for m in CORE if m in set(df.method)]

    rows, report = [], ["PAIRED HARDWARE ANALYSIS (Wilcoxon signed-rank on blocks)", ""]
    for m in methods:
        cells = []
        for c in conds:
            d = df[(df.method == m) & (df.profile == c)]
            sr, lo, hi = wilson_ci(int(d.success.sum()), len(d))
            cells.append("---" if np.isnan(sr) else f"{sr:.0f}\\,\\tiny[{lo:.0f},{hi:.0f}]")
        name = f"\\textbf{{{m}}}" if m == "Joint (ours)" else m
        rows.append(f"{name} & " + " & ".join(cells) + r" \\")

    ref = "Age-aware analytic rule"
    if "Joint (ours)" in methods and ref in methods:
        for c in conds:
            piv = (df[df.profile == c]
                   .pivot_table(index="block", columns="method",
                                values=args.metric, aggfunc="mean")
                   .dropna())
            if ref not in piv or "Joint (ours)" not in piv or len(piv) < 5:
                report.append(f"  {c}: insufficient complete blocks")
                continue
            a, b = piv["Joint (ours)"].to_numpy(), piv[ref].to_numpy()
            binary = set(np.unique(np.concatenate([a, b]))) <= {0.0, 1.0}
            if binary:
                # Paired binary outcomes: Wilcoxon is the wrong test and wastes
                # the pairing. McNemar's exact test uses only discordant blocks,
                # which is exactly the information the pairing provides.
                n01 = int(np.sum((a == 0) & (b == 1)))
                n10 = int(np.sum((a == 1) & (b == 0)))
                nd = n01 + n10
                if nd == 0:
                    report.append(f"  {c:<10} n_blocks={len(a):<4} "
                                  f"no discordant blocks -- no evidence either way")
                    continue
                pv = float(stats.binomtest(n10, nd, 0.5).pvalue)
                report.append(f"  {c:<10} n_blocks={len(a):<4} McNemar exact: "
                              f"ours-only wins={n10}, ref-only wins={n01}, p={pv:.4f}")
            else:
                diff = a - b
                if np.allclose(diff, 0):
                    report.append(f"  {c:<10} all blocks tied, n={len(diff)}")
                    continue
                _, pv = stats.wilcoxon(a, b)
                report.append(f"  {c:<10} n_blocks={len(diff):<4} Wilcoxon: "
                              f"median diff={np.median(diff):+.3f}  p={pv:.4f}")

    tab = ("\\begin{table}[t]\n\\caption{Hardware validation: success rate (\\%) "
           "with Wilson intervals; matched blocks per condition.}\\label{tab:hw}\n"
           "\\begin{tabular}{@{}l" + "c" * len(conds) + "@{}}\n\\toprule\nMethod & "
           + " & ".join(conds) + " \\\\\n\\midrule\n" + "\n".join(rows)
           + "\n\\botrule\n\\end{tabular}\n\\end{table}\n")

    with open(os.path.join(args.out, "tab_hw.tex"), "w") as f:
        f.write(tab)
    with open(os.path.join(args.out, "hardware_report.txt"), "w") as f:
        f.write("\n".join(report))
    print("\n".join(report))
    print(f"\nwrote {os.path.join(args.out, 'tab_hw.tex')}")
    return 0


# ---------------------------------------------------------------------------
def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    g = sub.add_parser("gate0", help="Stage 0 go/no-go verdict")
    g.add_argument("--csv", required=True)
    g.set_defaults(func=cmd_gate0)

    t = sub.add_parser("tables", help="generate all simulation LaTeX tables")
    t.add_argument("--csv", required=True)
    t.add_argument("--out", default="tables")
    t.set_defaults(func=cmd_tables)

    h = sub.add_parser("hardware", help="paired hardware analysis")
    h.add_argument("--csv", required=True)
    h.add_argument("--out", default="tables")
    h.add_argument("--metric", default="success")
    h.set_defaults(func=cmd_hardware)

    args = ap.parse_args()
    sys.exit(args.func(args))


if __name__ == "__main__":
    main()
