#!/usr/bin/env python3
"""
analyze.py -- turn raw episode logs into the LaTeX tables of the manuscript.

Write this BEFORE running the large experiments. Every table in the paper is
regenerated by one command, so a change to a weight, a threshold, or a seed set
costs a rerun rather than three days of retyping numbers.

Implements exactly the protocol of Sec. 5.8 of the manuscript:
  - interquartile mean (IQM) per cell, robust to the outlier episodes that
    dominate small-sample RL evaluations
  - 95% stratified bootstrap CI resampled over SEEDS, not episodes, because
    seeds are the unit of independence
  - Wilson intervals for binary outcomes
  - Mann-Whitney U on per-seed aggregates, with Cliff's delta as effect size
  - Holm-Bonferroni correction across the family of evaluation profiles
  - Wilcoxon signed-rank for the paired hardware blocks

INPUT (CSV, one row per episode). Required columns:
    method, profile, seed, episode, success, collision, nav_time
Optional columns are used when present:
    path_len, min_obs_dist, mean_scan_age, coupling_violation_rate,
    blocked_actions, safe_mode_frac, missed_decisions_frac, action_age, map

Hardware CSV additionally requires:  block   (the matched-triple id)

USAGE
    # Gate 0: does degradation actually break navigation?
    python3 analyze.py gate0 --csv stage0.csv

    # Full simulation tables
    python3 analyze.py tables --csv episodes.csv --out tables/

    # Paired hardware analysis
    python3 analyze.py hardware --csv hardware.csv --out tables/

Requires: numpy, pandas, scipy
"""

import argparse
import os
import sys

import numpy as np
import pandas as pd
from scipy import stats

RNG = np.random.default_rng(12345)   # fixed: CIs must be reproducible
N_BOOT = 10000

CORE = ["Default Nav2", "Age-aware analytic rule", "Joint (ours)"]
ABLATION = ["Nav-only", "QoS-only", "Joint (no superv.)", "Joint (off-board agent)"]
PROFILES = ["Normal", "Mild", "Moderate", "Severe", "Dynamic", "Trace"]
ABL_PROFILES = ["Normal", "Severe", "Trace"]


# ---------------------------------------------------------------------------
# Estimators
# ---------------------------------------------------------------------------
def iqm(x):
    """Interquartile mean: mean of the middle 50% of values."""
    x = np.asarray(x, dtype=float)
    x = x[~np.isnan(x)]
    if len(x) == 0:
        return np.nan
    if len(x) < 4:
        return float(np.mean(x))
    lo, hi = np.percentile(x, [25, 75])
    mid = x[(x >= lo) & (x <= hi)]
    return float(np.mean(mid)) if len(mid) else float(np.mean(x))


def stratified_bootstrap_ci(df, value_col, seed_col="seed", alpha=0.05,
                            n_boot=N_BOOT, statistic=iqm):
    """
    Resample SEEDS with replacement, then episodes within each drawn seed.
    Resampling episodes alone would understate uncertainty, because episodes
    within a seed share a trained policy and are not independent.
    """
    groups = [g[value_col].to_numpy(dtype=float) for _, g in df.groupby(seed_col)]
    groups = [g[~np.isnan(g)] for g in groups]
    groups = [g for g in groups if len(g)]
    if not groups:
        return (np.nan, np.nan, np.nan)
    point = statistic(np.concatenate(groups))
    n_seeds = len(groups)
    if n_seeds < 2:
        return (point, np.nan, np.nan)
    boots = np.empty(n_boot)
    for b in range(n_boot):
        idx = RNG.integers(0, n_seeds, n_seeds)
        pooled = []
        for i in idx:
            g = groups[i]
            pooled.append(g[RNG.integers(0, len(g), len(g))])
        boots[b] = statistic(np.concatenate(pooled))
    lo, hi = np.percentile(boots, [100 * alpha / 2, 100 * (1 - alpha / 2)])
    return (point, float(lo), float(hi))


def wilson_ci(k, n, z=1.96):
    """Wilson score interval for a binomial proportion (in percent)."""
    if n == 0:
        return (np.nan, np.nan, np.nan)
    p = k / n
    d = 1 + z * z / n
    centre = (p + z * z / (2 * n)) / d
    half = z * np.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / d
    return (100 * p, 100 * max(0.0, centre - half), 100 * min(1.0, centre + half))


def cliffs_delta(a, b):
    """Cliff's delta in [-1, 1]. Positive means a tends to exceed b."""
    a, b = np.asarray(a, float), np.asarray(b, float)
    if len(a) == 0 or len(b) == 0:
        return np.nan
    gt = sum((a[:, None] > b[None, :]).sum(axis=1))
    lt = sum((a[:, None] < b[None, :]).sum(axis=1))
    return float((gt - lt) / (len(a) * len(b)))


def delta_label(d):
    if np.isnan(d):
        return "--"
    m = abs(d)
    return "negligible" if m < 0.147 else "small" if m < 0.33 else \
           "medium" if m < 0.474 else "large"


def holm(pvals, labels):
    """Holm-Bonferroni. Returns {label: (p_raw, p_adj, reject_at_0.05)}."""
    order = np.argsort(pvals)
    m = len(pvals)
    adj = np.empty(m)
    running = 0.0
    for rank, i in enumerate(order):
        val = (m - rank) * pvals[i]
        running = max(running, val)
        adj[i] = min(1.0, running)
    return {labels[i]: (float(pvals[i]), float(adj[i]), bool(adj[i] < 0.05))
            for i in range(m)}


def per_seed(df, value_col):
    return df.groupby("seed")[value_col].mean().to_numpy(dtype=float)


# ---------------------------------------------------------------------------
# Gate 0
# ---------------------------------------------------------------------------
def cmd_gate0(args):
    df = pd.read_csv(args.csv)
    need = {"policy", "profile", "success", "nav_time"}
    missing = need - set(df.columns)
    if missing:
        sys.exit(f"stage0 CSV is missing columns: {sorted(missing)}")

    def cell(policy, profile):
        d = df[(df.policy == policy) & (df.profile == profile)]
        n = len(d)
        k = int(d.success.sum())
        sr, lo, hi = wilson_ci(k, n)
        t = d.loc[d.success == 1, "nav_time"]
        return dict(n=n, sr=sr, lo=lo, hi=hi,
                    t=float(t.mean()) if len(t) else np.nan)

    dn, ds = cell("default", "normal"), cell("default", "severe")
    cs = cell("conservative", "severe")

    print("\n=== Gate 0: does the problem exist in your setup? ===\n")
    print(f"{'cell':<28}{'n':>4}{'success %':>12}{'95% CI':>18}{'nav time s':>12}")
    for name, c in (("Default / Normal", dn), ("Default / Severe", ds),
                    ("Conservative / Severe", cs)):
        ci = f"[{c['lo']:.0f}, {c['hi']:.0f}]" if not np.isnan(c["lo"]) else "--"
        print(f"{name:<28}{c['n']:>4}{c['sr']:>12.1f}{ci:>18}{c['t']:>12.1f}")

    drop = dn["sr"] - ds["sr"]
    slow = (ds["t"] / dn["t"] - 1) * 100 if dn["t"] and not np.isnan(ds["t"]) else np.nan
    head = cs["sr"] - ds["sr"]

    if min(dn["n"], ds["n"], cs["n"]) < 30:
        print("\n[power] WARNING: fewer than 30 episodes per cell. At n=20 a "
              "success rate\n[power] carries a Wilson interval of roughly "
              "+/-20 points, which is wider than\n[power] the 15-point headroom "
              "threshold below. Run 40 episodes per cell --\n[power] Stage 0 "
              "episodes are short and this costs about an hour.")

    print("\n--- criteria ---")
    c1 = drop >= 20
    c2 = (not np.isnan(slow)) and slow >= 30
    c3 = head >= 15
    print(f"  success drop Normal->Severe : {drop:6.1f} pp   (need >= 20)   {'PASS' if c1 else 'fail'}")
    print(f"  nav-time increase           : {slow:6.1f} %    (need >= 30)   {'PASS' if c2 else 'fail'}")
    print(f"  headroom (consv - default)  : {head:6.1f} pp   (need >= 15)   {'PASS' if c3 else 'fail'}")

    ok = (c1 or c2) and c3
    print("\n>>> GATE 0: " + ("PASS -- proceed to Stage A.\n" if ok else "FAIL -- do NOT proceed.\n"))
    if not ok:
        print("  Degradation is not biting, or there is no headroom for any method")
        print("  to exploit. Increase severity, or increase the robot's reliance on")
        print("  the networked stream, then repeat. Do not build the DQN yet.\n")
    return 0 if ok else 1


# ---------------------------------------------------------------------------
# LaTeX emission
# ---------------------------------------------------------------------------
def _fmt(point, lo, hi, prec=1):
    if np.isnan(point):
        return "TBD"
    if np.isnan(lo):
        return f"{point:.{prec}f}"
    return f"{point:.{prec}f}\\,\\tiny[{lo:.{prec}f},{hi:.{prec}f}]"


def matrix_table(df, methods, profiles, value_col, caption, label,
                 percent=False, prec=1, star=True, statistic=None):
    # IQM is the right estimator for continuous returns, but it saturates on
    # binary outcomes (the middle 50% of mostly-ones is all ones). Binary rates
    # use the plain proportion instead.
    if statistic is None:
        statistic = np.mean if percent else iqm
    rows = []
    for m in methods:
        cells = []
        for p in profiles:
            d = df[(df.method == m) & (df.profile == p)]
            if d.empty:
                cells.append("---")
                continue
            if percent:
                point, lo, hi = stratified_bootstrap_ci(
                    d.assign(_v=d[value_col] * 100.0), "_v", statistic=statistic)
            else:
                point, lo, hi = stratified_bootstrap_ci(d, value_col,
                                                        statistic=statistic)
            cells.append(_fmt(point, lo, hi, prec))
        name = f"\\textbf{{{m}}}" if m == "Joint (ours)" else m
        rows.append(f"{name} & " + " & ".join(cells) + r" \\")
    cols = "@{}l" + "c" * len(profiles) + "@{}"
    head = " & ".join(profiles)
    est = "proportion" if statistic is np.mean else "IQM"
    note = (f" Cells give the {est} with a 95\\% stratified bootstrap CI "
            "over seeds." if star else "")
    return (f"\\begin{{table*}}[t]\n\\caption{{{caption}{note}}}\\label{{{label}}}\n"
            f"\\begin{{tabular}}{{{cols}}}\n\\toprule\nMethod & {head} \\\\\n\\midrule\n"
            + "\n".join(rows) + "\n\\botrule\n\\end{tabular}\n\\end{table*}\n")


def comparison_report(df, method_a, method_b, profiles, value_col):
    """Mann-Whitney on per-seed aggregates + Cliff's delta + Holm across profiles."""
    ps, ds, labels, absd = [], [], [], []
    for p in profiles:
        a = per_seed(df[(df.method == method_a) & (df.profile == p)], value_col)
        b = per_seed(df[(df.method == method_b) & (df.profile == p)], value_col)
        if len(a) < 2 or len(b) < 2:
            continue
        try:
            _, pv = stats.mannwhitneyu(a, b, alternative="two-sided")
        except ValueError:
            pv = 1.0
        ps.append(pv)
        ds.append(cliffs_delta(a, b))
        absd.append(float(np.mean(a) - np.mean(b)))
        labels.append(p)
    if not ps:
        return "  (insufficient seeds for comparison)\n"
    res = holm(ps, labels)
    # The absolute difference comes first: practical magnitude is what a service
    # robotics reader acts on, and a large gap with a weak p-value at 5-8 seeds
    # is a statement about power, not about the effect being absent.
    out = [f"  {method_a}  vs  {method_b}   [{value_col}]",
           f"  {'profile':<12}{'abs diff':>10}{'delta':>8}  {'magnitude':<11}"
           f"{'p_raw':>9}{'p_holm':>9}  sig"]
    for lab, d, ad in zip(labels, ds, absd):
        praw, padj, rej = res[lab]
        out.append(f"  {lab:<12}{ad:>+10.3f}{d:>8.2f}  {delta_label(d):<11}"
                   f"{praw:>9.4f}{padj:>9.4f}  {'YES' if rej else '.'}")
    return "\n".join(out) + "\n"


def power_warning(n_seeds, n_family):
    """
    Mann-Whitney on n vs n seeds has a hard p-value floor of 2/C(2n, n).
    With 5 seeds that floor is 0.0079; corrected across a family of six
    profiles it becomes 0.048 -- so at most ONE profile can ever reach
    significance, and only under perfect separation. This is a property of the
    test, not of the data, and no amount of extra episodes fixes it.
    """
    from math import comb
    floor = 2 / comb(2 * n_seeds, n_seeds)
    adj = min(1.0, floor * max(1, n_family))
    msg = (f"\n[power] {n_seeds} seeds -> minimum attainable p = {floor:.4f}; "
           f"after Holm over {n_family} profiles = {adj:.4f}")
    if adj >= 0.05:
        msg += ("\n[power] WARNING: significance is UNREACHABLE for this family "
                "at this seed count.\n[power] Raise seeds for the core methods "
                "(8 gives a floor of 0.0009), or shrink the family.")
    return msg


def cmd_tables(args):
    df = pd.read_csv(args.csv)
    os.makedirs(args.out, exist_ok=True)
    profs = [p for p in PROFILES if p in set(df.profile)]
    abl_profs = [p for p in ABL_PROFILES if p in set(df.profile)]
    core = [m for m in CORE if m in set(df.method)]
    allm = [m for m in CORE + ABLATION if m in set(df.method)]

    written = []

    def w(fn, text):
        with open(os.path.join(args.out, fn), "w") as f:
            f.write(text)
        written.append(fn)

    w("tab_success.tex", matrix_table(
        df, allm, profs, "success",
        "Navigation success rate (\\%) by method and held-out network profile.",
        "tab:success", percent=True))

    if "collision" in df.columns:
        w("tab_collision.tex", matrix_table(
            df, allm, profs, "collision",
            "Collision rate (\\%) by method and held-out network profile.",
            "tab:collision", percent=True))

    if "nav_time" in df.columns:
        w("tab_navtime.tex", matrix_table(
            df, allm, profs, "nav_time",
            "Navigation time (s) by method and held-out network profile.",
            "tab:navtime"))

    if "coupling_violation_rate" in df.columns:
        w("tab_violation.tex", matrix_table(
            df, allm, profs, "coupling_violation_rate",
            "Fraction of control cycles violating Eq.~\\eqref{eq:coupling}, "
            "by method and profile.", "tab:violation", percent=True, prec=2))

    # Statistical comparisons: the pre-registered primary hypothesis first.
    lines = ["PRIMARY HYPOTHESIS (pre-registered)",
             "  Joint (ours) > Age-aware analytic rule, success rate,",
             "  on the held-out Dynamic and Trace profiles.", ""]
    primary = [p for p in ("Dynamic", "Trace") if p in profs]
    if primary and {"Joint (ours)", "Age-aware analytic rule"} <= set(df.method):
        lines.append(comparison_report(df, "Joint (ours)",
                                       "Age-aware analytic rule", primary, "success"))
    lines += ["", "SECONDARY COMPARISONS (report as secondary)", ""]
    for other in [m for m in allm if m not in ("Joint (ours)",)]:
        if other == "Age-aware analytic rule":
            lines.append(comparison_report(df, "Joint (ours)", other,
                                           [p for p in profs if p not in primary],
                                           "success"))
        else:
            sub = abl_profs if other in ABLATION else profs
            lines.append(comparison_report(df, "Joint (ours)", other, sub, "success"))
    w("stats_report.txt", "\n".join(lines))

    # Per-seed appendix table.
    if core:
        g = (df.groupby(["method", "profile", "seed"])["success"]
               .mean().mul(100).round(1).reset_index())
        w("per_seed.csv", g.to_csv(index=False))

    print("wrote:")
    for fn in written:
        print("  ", os.path.join(args.out, fn))
    n_seeds = int(df.groupby(["method", "profile"])["seed"].nunique().min())
    warn = power_warning(n_seeds, len(profs))
    with open(os.path.join(args.out, "stats_report.txt"), "a") as f:
        f.write(warn + "\n")
    print("\n--- statistical summary ---")
    print("\n".join(lines[:40]))
    print(warn)
    return 0


